-- Bootstrap inicial do Professor IA | AçõesJA
-- Execute uma vez no SQL Editor do Supabase ou com:
-- psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -f supabase/bootstrap.sql
-- O script é idempotente e não contém credenciais.

begin;

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_email_lowercase check (email = lower(email)),
  constraint profiles_full_name_length check (full_name is null or char_length(full_name) <= 120)
);

create unique index if not exists profiles_email_lower_key on public.profiles (lower(email));

create table if not exists public.launch_waitlist_entries (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  full_name text,
  whatsapp text,
  marketing_consent boolean not null default false,
  attribution jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint launch_waitlist_email_lowercase check (email = lower(email)),
  constraint launch_waitlist_full_name_length check (full_name is null or char_length(full_name) <= 120),
  constraint launch_waitlist_whatsapp_length check (whatsapp is null or char_length(whatsapp) <= 30),
  constraint launch_waitlist_attribution_object check (jsonb_typeof(attribution) = 'object')
);

create unique index if not exists launch_waitlist_entries_email_key
  on public.launch_waitlist_entries (lower(email));

-- Catálogo pequeno e intencional do experimento da LP. Não representa a
-- cobertura total de ativos da plataforma principal.
create table if not exists public.professor_demo_assets (
  ticker text primary key,
  display_name text not null,
  display_order smallint not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint professor_demo_assets_ticker_format check (ticker ~ '^[A-Z]{4}[0-9]{1,2}$'),
  constraint professor_demo_assets_display_name_present check (char_length(trim(display_name)) between 2 and 120)
);

create table if not exists public.professor_standard_questions (
  question_key text primary key,
  question_text text not null unique,
  display_order smallint not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint professor_standard_questions_key_format check (question_key ~ '^[a-z0-9_]+$'),
  constraint professor_standard_questions_text_present check (char_length(trim(question_text)) between 10 and 280)
);

create table if not exists public.professor_standard_answers (
  ticker text not null references public.professor_demo_assets(ticker) on delete cascade,
  question_key text not null references public.professor_standard_questions(question_key) on delete cascade,
  answer_markdown text not null,
  investigation_hint text not null,
  source_label text not null default 'Conteúdo educacional AçõesJA',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (ticker, question_key),
  constraint professor_standard_answers_answer_present check (char_length(trim(answer_markdown)) between 40 and 6000),
  constraint professor_standard_answers_hint_present check (char_length(trim(investigation_hint)) between 10 and 1000)
);

-- Eventos de validação não guardam pergunta livre, resposta, e-mail ou
-- outro dado digitado. O session_id é aleatório e local ao navegador.
create table if not exists public.lp_interaction_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  session_id uuid not null,
  user_id uuid references auth.users(id) on delete set null,
  event_name text not null,
  ticker text references public.professor_demo_assets(ticker) on delete set null,
  question_key text references public.professor_standard_questions(question_key) on delete set null,
  properties jsonb not null default '{}'::jsonb,
  constraint lp_interaction_events_name_format check (event_name ~ '^[a-z][a-z0-9_]{2,63}$'),
  constraint lp_interaction_events_properties_object check (jsonb_typeof(properties) = 'object'),
  constraint lp_interaction_events_properties_size check (octet_length(properties::text) <= 2048)
);

create index if not exists lp_interaction_events_occurred_at_idx
  on public.lp_interaction_events (occurred_at desc);
create index if not exists lp_interaction_events_event_name_idx
  on public.lp_interaction_events (event_name, occurred_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name, avatar_url)
  values (
    new.id,
    lower(coalesce(new.email, '')),
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'avatar_url', '')
  )
  on conflict (id) do update
  set email = excluded.email,
      full_name = coalesce(excluded.full_name, public.profiles.full_name),
      avatar_url = coalesce(excluded.avatar_url, public.profiles.avatar_url),
      updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
  for each row execute procedure public.set_updated_at();

drop trigger if exists launch_waitlist_set_updated_at on public.launch_waitlist_entries;
create trigger launch_waitlist_set_updated_at before update on public.launch_waitlist_entries
  for each row execute procedure public.set_updated_at();

drop trigger if exists professor_demo_assets_set_updated_at on public.professor_demo_assets;
create trigger professor_demo_assets_set_updated_at before update on public.professor_demo_assets
  for each row execute procedure public.set_updated_at();

drop trigger if exists professor_standard_questions_set_updated_at on public.professor_standard_questions;
create trigger professor_standard_questions_set_updated_at before update on public.professor_standard_questions
  for each row execute procedure public.set_updated_at();

drop trigger if exists professor_standard_answers_set_updated_at on public.professor_standard_answers;
create trigger professor_standard_answers_set_updated_at before update on public.professor_standard_answers
  for each row execute procedure public.set_updated_at();

