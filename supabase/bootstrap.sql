-- Entrada pública mínima para a lista de lançamento. A tabela continua privada.
create or replace function public.join_launch_waitlist(
  p_email text,
  p_full_name text default null,
  p_whatsapp text default null,
  p_marketing_consent boolean default false,
  p_attribution jsonb default '{}'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(trim(p_email));
  v_id uuid;
begin
  if v_email !~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$' then
    raise exception 'E-mail inválido' using errcode = '22023';
  end if;

  if nullif(trim(p_full_name), '') is null then
    raise exception 'Nome é obrigatório' using errcode = '22023';
  end if;

  if coalesce(p_marketing_consent, false) is not true then
    raise exception 'O consentimento para receber avisos e novidades é obrigatório' using errcode = '22023';
  end if;

  if jsonb_typeof(coalesce(p_attribution, '{}'::jsonb)) <> 'object' then
    raise exception 'Atribuição inválida' using errcode = '22023';
  end if;

  insert into public.launch_waitlist_entries (
    user_id, email, full_name, whatsapp, marketing_consent, attribution
  ) values (
    auth.uid(), v_email, nullif(trim(p_full_name), ''), nullif(trim(p_whatsapp), ''),
    p_marketing_consent, coalesce(p_attribution, '{}'::jsonb)
  )
  on conflict (lower(email)) do update set
    user_id = coalesce(excluded.user_id, public.launch_waitlist_entries.user_id),
    full_name = coalesce(excluded.full_name, public.launch_waitlist_entries.full_name),
    whatsapp = coalesce(excluded.whatsapp, public.launch_waitlist_entries.whatsapp),
    marketing_consent = public.launch_waitlist_entries.marketing_consent or excluded.marketing_consent,
    attribution = public.launch_waitlist_entries.attribution || excluded.attribution,
    updated_at = now()
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.get_professor_standard_answer(
  p_ticker text,
  p_question_key text
)
returns table (
  ticker text,
  asset_name text,
  question_key text,
  question_text text,
  answer_markdown text,
  investigation_hint text,
  source_label text
)
language sql
stable
security definer
set search_path = ''
as $$
  select a.ticker, a.display_name, q.question_key, q.question_text,
         r.answer_markdown, r.investigation_hint, r.source_label
  from public.professor_standard_answers r
  join public.professor_demo_assets a on a.ticker = r.ticker
  join public.professor_standard_questions q on q.question_key = r.question_key
  where r.ticker = upper(trim(p_ticker))
    and r.question_key = trim(p_question_key)
    and r.active and a.active and q.active
  limit 1;
$$;

create or replace function public.record_lp_interaction(
  p_session_id uuid,
  p_event_name text,
  p_ticker text default null,
  p_question_key text default null,
  p_properties jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
  v_ticker text := nullif(upper(trim(p_ticker)), '');
  v_question_key text := nullif(trim(p_question_key), '');
  v_properties jsonb := coalesce(p_properties, '{}'::jsonb);
begin
  if p_session_id is null then
    raise exception 'Sessão anônima inválida' using errcode = '22023';
  end if;
  if p_event_name !~ '^[a-z][a-z0-9_]{2,63}$' then
    raise exception 'Evento inválido' using errcode = '22023';
  end if;
  if jsonb_typeof(v_properties) <> 'object' or octet_length(v_properties::text) > 2048 then
    raise exception 'Propriedades inválidas' using errcode = '22023';
  end if;

  insert into public.lp_interaction_events (
    session_id, user_id, event_name, ticker, question_key, properties
  ) values (
    p_session_id, auth.uid(), p_event_name, v_ticker, v_question_key, v_properties
  ) returning id into v_id;

  return v_id;
end;
$$;

